<?php

return [

    /*
    |--------------------------------------------------------------------------
    | R-WHILE 処理系の実行ファイル
    |--------------------------------------------------------------------------
    |
    | src/ を `make install` すると bin/ri に置かれる。Web からは配信されない
    | 場所であること（かつては public/ri に置いており、実行ファイルがそのまま
    | ダウンロードできる状態だった）。
    |
    */

    'ri_bin' => env('RWHILE_RI_BIN') ?: base_path('bin/ri'),

    /*
    |--------------------------------------------------------------------------
    | 1 回の実行に許す秒数
    |--------------------------------------------------------------------------
    |
    | R-WHILE は停止しないプログラムを書けるので、上限は必須である
    | （同梱の examples/infinite.rwhile は意図的な非停止例）。
    |
    */

    'timeout' => (int) env('RWHILE_TIMEOUT', 10),

    /*
    |--------------------------------------------------------------------------
    | 受け付けるソース・データの最大バイト数
    |--------------------------------------------------------------------------
    */

    'max_input_bytes' => (int) env('RWHILE_MAX_INPUT_BYTES', 256 * 1024),

    /*
    |--------------------------------------------------------------------------
    | 1 回の実行に許すメモリ（MB）と、それを掛ける道具
    |--------------------------------------------------------------------------
    |
    | R-WHILE では「止まらないうえに際限なく確保し続ける」プログラムが書ける。
    | 同梱の examples/infinite.rwhile がまさにそれで、10 秒で 192MB まで伸びる
    | （2026-09-08 実測）。時間制限だけでは本番のメモリを守れない。
    |
    | RLIMIT_DATA を使う。RLIMIT_AS だと OCaml ランタイムが予約する仮想アドレス空間
    | まで数えてしまい、256MB では正常な例題すら通らなかった。128MB の
    | RLIMIT_DATA なら同梱の例題 5 種はすべて通り、上の非停止例は中断される。
    |
    | --core=0 も併せて渡す。s1 の core_pattern は "core"（相対パス）なので、
    | 上限に当たって abort するたびに作業ディレクトリへ core が落ちてしまう。
    |
    */

    'memory_limit_mb' => (int) env('RWHILE_MEMORY_LIMIT_MB', 128),

    'prlimit_bin' => env('RWHILE_PRLIMIT_BIN', '/usr/bin/prlimit'),

    /*
    |--------------------------------------------------------------------------
    | 同時に走らせる実行の数
    |--------------------------------------------------------------------------
    |
    | throttle は 1 つの相手からの毎分の回数を抑えるだけで、同時に走る本数は
    | 抑えない（1 回が最大 RWHILE_TIMEOUT 秒走るので重なる）。相手が増えれば
    | いくらでも重なるため、サーバ全体で本数に蓋をする。
    | 最悪でも memory_limit_mb × max_concurrent しか使わない。
    |
    */

    'max_concurrent' => (int) env('RWHILE_MAX_CONCURRENT', 3),

];
